'use strict';
/**
 * compiler/emit-emerge.js — T0 + T1 for specs whose target language is Emerge
 * UUID: spec-compiler-emit-emerge-v1-0000-2026-1028-jamesbrooks-001
 * Version: 1.0.0
 *
 * §2026-10-28 — emit.js only knew TypeScript. A spec with meta.language_stack: [emerge] now gets:
 *   T0  one .eg file and one .test.eg file per module, at the paths its build plan names (compiler/target.js),
 *       holding the module's header only. No package.json, no tsconfig.json, no .ts.
 *   T1  the scaffold: one fn stub per export that can be an Emerge fn, which raises "not implemented" (§1.3: a stub
 *       fails loudly, never returns a fake value); gate pipeline, contracts and error paths as comments; the test file
 *       carries one commented test per contract and error path for T2 to fill.
 *
 * Every stub is checked by the real Emerge checker (lang/index.js compileSource) before it is written. An export that
 * would not compile, or would redefine a builtin, is written as a comment with the checker's reason, never dropped.
 *
 * Overwrite rule: a file is written only if it does not exist or still starts with GENERATED_MARK. Code that T2 or a
 * person wrote (no mark) is never overwritten.
 *
 * Modules the build plan marks built or blocked by a decision are not emitted (tier DONE / DEFERRED).
 * Zero LLM calls (§CC-002). Deterministic: same spec → same bytes.
 */

const fs   = require('fs');
const path = require('path');
const { buildDecision, modulePaths } = require('./target');

const GENERATED_MARK = '// GENERATED by spec-compiler';
const EG_TYPES = new Set(['int', 'num', 'float', 'string', 'bool', 'bytes', 'list', 'map', 'fn', 'any']);

let lang = null;
function checker() {
  if (lang === null) {
    try { lang = require('../lang'); } catch { lang = false; }
  }
  return lang || null;
}

/** compiles(src) → null when it compiles, else the first error message. */
function compileError(src) {
  const l = checker();
  if (!l) return null;                     // no checker available: emit, and say so in the header
  try {
    const r = l.compileSource(src, 'stub.eg');
    return r.errors && r.errors.length ? String(r.errors[0].message ?? r.errors[0]) : null;
  } catch (e) { return String(e.message ?? e); }
}

function writer(outputDir) {
  const emitted = [], skipped = [], failures = [];
  function write(rel, content) {
    const abs = path.join(outputDir, rel);
    try {
      if (fs.existsSync(abs)) {
        const head = fs.readFileSync(abs, 'utf8').slice(0, 200);
        if (!head.startsWith(GENERATED_MARK)) { skipped.push({ name: rel, reason: 'exists_not_generated' }); return; }
      }
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, content, 'utf8');
      emitted.push(rel);
    } catch (e) { failures.push({ file: rel, error: e.message }); }
  }
  return { write, emitted, skipped, failures };
}

/** Split "a(x) → T · b(y) → U" into single signatures and parse each. */
function exportsOf(mod) {
  const out = [];
  for (const raw of mod.exports ?? []) {
    for (const part of String(raw).split(/\s+·\s+/)) {
      const m = part.trim().match(/^([A-Za-z_][A-Za-z0-9_]*)\s*\(([^)]*)\)\s*(?:(?:→|->)\s*(.*))?$/);
      out.push(m ? { ok: true, text: part.trim(), name: m[1], params: m[2], returns: (m[3] ?? '').trim() } : { ok: false, text: part.trim() });
    }
  }
  return out;
}

function egType(t) {
  const s = String(t ?? '').trim().toLowerCase().replace(/\?$/, '');
  return EG_TYPES.has(s) ? (s === 'float' ? 'num' : s) : null;
}

function egParams(params) {
  const names = []; const seen = new Set();
  for (const p of params.split(',').map(s => s.trim()).filter(Boolean)) {
    const m = p.match(/^([A-Za-z_][A-Za-z0-9_]*)\s*(?::\s*(.+))?$/);
    if (!m || seen.has(m[1])) continue;
    seen.add(m[1]);
    const t = egType(m[2]);
    names.push(t ? `${m[1]}: ${t}` : m[1]);
  }
  return names.join(', ');
}

/** true when name already resolves in Emerge without being defined: a builtin or prelude fn. */
function isBuiltin(name) {
  return !!checker() && compileError(`let probe_builtin = ${name}`) === null;
}

function stubFor(mod, ex) {
  const id = mod.id ?? mod.name;
  // A stub with a builtin's name would shadow it inside the module, so every call to the builtin would raise.
  if (isBuiltin(ex.name)) return { ok: false, src: '', err: `already a builtin (${ex.name}); not redefined` };
  const ret = egType((ex.returns.match(/^[A-Za-z]+\??/) ?? [''])[0]);   // first word: "bytes   (u32 …)" → bytes
  const src = `fn ${ex.name}(${egParams(ex.params)})${ret ? ': ' + ret : ''} {\n  raise("${mod.name ?? id}.${ex.name}: not implemented (spec ${id})")\n}`;
  const err = compileError(src);
  return err ? { ok: false, src, err } : { ok: true, src };
}

const comment = (label, items) => items.length ? [`// ── ${label} ${'─'.repeat(Math.max(4, 70 - label.length))}`, ...items.map(s => `// ${s}`), ''] : [];

function header(mod, meta, kind) {
  return [
    `${GENERATED_MARK} (${kind}) — remove this line once the module is implemented, so it is never overwritten.`,
    `// module: ${mod.name ?? mod.id}   id: ${mod.id ?? '-'}   uuid: ${mod.uuid ?? 'MISSING-UUID'}`,
    `// spec: ${meta.name ?? 'unknown'} v${meta.version ?? '?'}${mod.spec_ref ? '   section: ' + mod.spec_ref : ''}`,
    ...(mod.build?.next ? [`// next step: ${mod.build.next}`] : []),
    ...(checker() ? [] : ['// NOTE: the Emerge checker was not available when this was generated; stubs are unchecked.']),
    '',
  ];
}

async function emitT0Emerge(parsedSpec, outputDir) {
  const meta = parsedSpec.meta ?? {};
  const w = writer(outputDir);
  for (const mod of parsedSpec.modules ?? []) {
    const gate = buildDecision(mod);
    if (gate) { w.skipped.push({ name: mod.name ?? mod.id, reason: gate.reason }); continue; }
    const p = modulePaths(mod, meta);
    w.write(p.impl, [...header(mod, meta, 'T0 structure'), `// ${String(mod.description ?? '').trim().replace(/\s+/g, ' ')}`, '// TODO: T1 scaffold pending', ''].join('\n'));
    w.write(p.test, [...header(mod, meta, 'T0 structure'), `use "${path.basename(p.impl)}" as m`, '', '// TODO: T1 test scaffold pending', ''].join('\n'));
  }
  return { tier: 0, language: 'emerge', emitted: w.emitted, skipped: w.skipped, failures: w.failures, outputDir,
    moduleCount: (parsedSpec.modules ?? []).length, eventCount: 0, schemaCount: (parsedSpec.schemas ?? []).length };
}

async function emitT1Emerge(parsedSpec, outputDir, opts = {}) {
  const meta = parsedSpec.meta ?? {};
  const w = writer(outputDir);
  const { readinessOf = null, minReadiness = 0.5 } = opts;
  for (const mod of parsedSpec.modules ?? []) {
    const name = mod.name ?? mod.id;
    const gate = buildDecision(mod);
    if (gate) { w.skipped.push({ name, reason: gate.reason }); continue; }
    const r = readinessOf ? readinessOf(mod) : 1;
    if (r < minReadiness) { w.skipped.push({ name, reason: `genReadiness ${r.toFixed(2)} below T1 minimum (${minReadiness})` }); continue; }

    const p = modulePaths(mod, meta);
    const exs = exportsOf(mod);
    const stubs = exs.filter(e => e.ok).map(e => ({ e, s: stubFor(mod, e) }));
    const notFns = exs.filter(e => !e.ok).map(e => e.text);
    const refused = stubs.filter(x => !x.s.ok).map(x => `${x.e.text}   — not emitted: ${x.s.err}`);

    w.write(p.impl, [
      ...header(mod, meta, 'T1 scaffold'),
      ...comment('Purpose', [String(mod.description ?? '').trim().replace(/\s+/g, ' ')]),
      ...comment('Gate pipeline', (mod.gate_pipeline ?? []).map(String)),
      ...comment('Behavioral contracts', (mod.behavioral_contracts ?? []).map(String)),
      ...comment('Error paths (each is a gap, never a silent failure)', (mod.error_paths ?? []).map(String)),
      ...comment('Exports that are not plain functions (hooks, commands)', notFns),
      ...comment('Exports not emitted as stubs', refused),
      ...stubs.filter(x => x.s.ok).flatMap(x => [`// ${x.e.text}`, x.s.src, '']),
    ].join('\n'));

    const pending = [
      ...(mod.behavioral_contracts ?? []).map(c => ['contract', String(c)]),
      ...(mod.error_paths ?? []).map(e => ['error path', String(e)]),
    ];
    w.write(p.test, [
      ...header(mod, meta, 'T1 test scaffold'),
      `use "${path.basename(p.impl)}" as m`,
      '',
      '// One test per contract and error path. T2 writes the body and removes the comment markers.',
      '',
      ...pending.flatMap(([k, t], i) => [
        `// test "${name} ${k} ${i + 1}: ${t.replace(/"/g, "'").slice(0, 90)}" {`,
        `//   expect false, "pending"`,
        `// }`,
        '',
      ]),
    ].join('\n'));
  }
  return { tier: 1, language: 'emerge', emitted: w.emitted, skipped: w.skipped, failures: w.failures, outputDir, moduleCount: (parsedSpec.modules ?? []).length };
}

module.exports = { emitT0Emerge, emitT1Emerge, exportsOf, GENERATED_MARK, MODULE_ID: 'spec-compiler-emit-emerge', VERSION: '1.0.0' };
